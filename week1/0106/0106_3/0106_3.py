class Person:
    """
    Класс, представляющий сотрудника с именем, фамилией и квалификацией.
    """

    def __init__(self, name, surname, qualification=1):
        """
        Конструктор класса Person.

        :param name: Имя сотрудника.
        :param surname: Фамилия сотрудника.
        :param qualification: Квалификация сотрудника (по умолчанию 1).
        """
        self.name = name  # Сохраняем имя сотрудника
        self.surname = surname  # Сохраняем фамилию сотрудника
        self.qualification = qualification  # Сохраняем квалификацию сотрудника

    def get_info(self):
        """
        Возвращает строку с информацией о сотруднике.

        :return: Строка с информацией о сотруднике.
        """
        return f"Имя: {self.name}, Фамилия: {self.surname}, Квалификация: {self.qualification}"

    def __del__(self):
        """
        Деструктор класса Person.  Выводит прощальное сообщение при удалении объекта.
        """
        print(f"До свидания, мистер {self.name} {self.surname}")


# Основная ветка программы
if __name__ == "__main__":
    # Создаем три объекта класса Person
    person1 = Person("Иван", "Иванов", 3)  # Сотрудник с квалификацией 3
    person2 = Person("Петр", "Петров", 2)  # Сотрудник с квалификацией 2
    person3 = Person("Сидор", "Сидоров")  # Сотрудник с квалификацией по умолчанию (1)

    # Выводим информацию о сотрудниках
    print(person1.get_info())
    print(person2.get_info())
    print(person3.get_info())

    # Увольняем самое слабое звено (сотрудника с наименьшей квалификацией)
    print("\nУвольняем самое слабое звено...")
    del person3  # Удаляем объект person3

    # Добавляем функцию input(), чтобы скрипт не завершился сразу
    input("\nНажмите Enter для завершения программы...")
